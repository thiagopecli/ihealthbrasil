export function getTranslation(lang, path) {
  const keys = path.split('.')
  let value = translations[lang] || translations.pt

  for (const key of keys) {
    value = value?.[key]
  }

  if (!value && lang !== 'pt') {
    return getTranslation('pt', path)
  }

  return value || path
}

export function t(lang, key) {
  return getTranslation(lang, key)
}

export function getCurrentLanguage() {
  const saved = localStorage.getItem('ihealthbrasil-language')
  return saved || 'pt'
}

export function setLanguage(lang) {
  localStorage.setItem('ihealthbrasil-language', lang)
}

